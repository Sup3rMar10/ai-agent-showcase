"""Build results/RESULTS.md and results/agent.png from results/agent.*.json."""
import glob
import json
import os

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

RES = "results"
CATS = ["lookup", "filter", "calc", "date", "not-found"]
COLORS = {"Qwen2.5-1.5B-Instruct": "#2a9d8f", "Qwen2.5-0.5B-Instruct": "#9aa5b1"}


def pct(x):
    return "n/a" if x is None else f"{x:.0%}"


def load_runs():
    runs = []
    for p in sorted(glob.glob(os.path.join(RES, "agent.*.json"))):
        with open(p, encoding="utf-8") as f:
            runs.append(json.load(f))
    return runs


def short(run):
    return run["model"].split("/")[-1]


def tables(runs):
    lines = ["# Results\n", "Generated by `python -m src.report` from `results/agent.*.json`. 16 tasks, greedy decoding.\n",
             "| Model | Correct answers | Used the expected tools | Finished with an answer | Avg steps | Avg errors/task | s/task |",
             "|---|---|---|---|---|---|---|"]
    for r in runs:
        s = r["summary"]
        n_ok = round(s["accuracy"] * s["n_tasks"])
        lines.append(f"| {short(r)} | {pct(s['accuracy'])} ({n_ok}/{s['n_tasks']}) | {pct(s['used_expected_tools'])} | "
                     f"{pct(s['finished_rate'])} | {s['avg_steps']:.1f} | {s['avg_errors_per_task']:.1f} | "
                     f"{s['avg_seconds_per_task']:.0f} |")
    lines += ["", "Correct answers by task type:\n", "| Model | " + " | ".join(CATS) + " |", "|---|" + "---|" * len(CATS)]
    for r in runs:
        bc = r["summary"]["by_category"]
        cells = [f"{pct(bc[c]['accuracy'])} (n={bc[c]['n']})" if c in bc else "-" for c in CATS]
        lines.append(f"| {short(r)} | " + " | ".join(cells) + " |")
    lines += ["", "Per-task outcomes (`OK`/`x`, steps taken):\n", "| Task | Question | " + " | ".join(short(r) for r in runs) + " |",
              "|---|---|" + "---|" * len(runs)]
    by_model = [{t["id"]: t for t in r["tasks"]} for r in runs]
    for t in runs[0]["tasks"]:
        cells = [f"{'OK' if m[t['id']]['correct'] else 'x'} ({m[t['id']]['n_steps']})" if t["id"] in m else "-" for m in by_model]
        lines.append(f"| {t['id']} | {t['question']} | " + " | ".join(cells) + " |")
    return lines


def plot(runs):
    fig, ax = plt.subplots(figsize=(7.5, 3.6))
    w = 0.8 / len(runs)
    for k, r in enumerate(runs):
        xs = [i + (k - (len(runs) - 1) / 2) * w for i in range(len(CATS))]
        vals = [r["summary"]["by_category"].get(c, {"accuracy": 0})["accuracy"] * 100 for c in CATS]
        ax.bar(xs, vals, w, label=short(r), color=COLORS.get(short(r)))
        for x, v in zip(xs, vals, strict=True):
            ax.text(x, v + 1.5, f"{v:.0f}", ha="center", fontsize=8)
    ax.set_xticks(range(len(CATS)))
    ax.set_xticklabels(CATS)
    ax.set_ylim(0, 110)
    ax.set_ylabel("% of tasks answered correctly")
    ax.set_title("Tool-using agent: accuracy by task type (16 tasks)", fontsize=10)
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(os.path.join(RES, "agent.png"), dpi=150)


def main():
    runs = load_runs()
    if not runs:
        raise SystemExit("no results/agent.*.json found; run python -m src.evaluate first")
    with open(os.path.join(RES, "RESULTS.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(tables(runs)) + "\n")
    plot(runs)
    print("wrote RESULTS.md and agent.png")


if __name__ == "__main__":
    main()
